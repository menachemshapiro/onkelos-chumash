def fetch(word):
    url = "https://www.sefaria.org/api/words/" + urllib.parse.quote(word) + "?always_consonants=1"
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json"})
    for attempt in range(6):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                data = json.loads(r.read().decode("utf-8"))
            break
        except urllib.error.HTTPError as e:
            if e.code == 404: return []
            wait = 30 * (attempt + 1) if e.code == 429 else 5 * (attempt + 1)
            print(f"  server said {e.code}; waiting {wait}s and trying again")
            time.sleep(wait)
        except Exception as e:
            print(f"  network problem ({e}); waiting 10s and trying again")
            time.sleep(10)
    else:
        raise SystemExit("Too many failures in a row. Check your internet connection and run the script again; it will continue where it stopped.")
    if not isinstance(data, list): return []
    out = []
    for d in data:
        if d.get("parent_lexicon") == "Jastrow Dictionary":
            d.pop("parent_lexicon_details", None)
            out.append(d)
    return out

def main():
    done = {}
    if os.path.exists(PROGRESS):
        with open(PROGRESS, encoding="utf-8") as f:
            for line in f:
                try: rec = json.loads(line); done[rec["q"]] = rec["r"]
                except Exception: pass
    todo = [q for q in QUERIES if q not in done]
    print(f"{len(QUERIES)} words; {len(done)} already done; {len(todo)} to go")
    t0 = time.time()
    with open(PROGRESS, "a", encoding="utf-8") as f:
        for i, q in enumerate(todo, 1):
            r = fetch(q)
            f.write(json.dumps({"q": q, "r": r}, ensure_ascii=False) + "\n"); f.flush()
            done[q] = r
            if i % 50 == 0 or i == len(todo):
                left = (time.time() - t0) / i * (len(todo) - i)
                print(f"  {i}/{len(todo)} done, about {int(left // 60)} min left")
            time.sleep(PAUSE)
    entries, by_query = {}, {}
    for q in QUERIES:
        ids = []
        for d in done.get(q, []):
            key = d.get("rid") or d.get("headword")
            entries[key] = d; ids.append(key)
        by_query[q] = ids
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"source": "Sefaria API, Jastrow Dictionary (London, Luzac, 1903; public domain)",
                   "fetched": time.strftime("%Y-%m-%d"), "queries": by_query, "entries": entries}, f, ensure_ascii=False)
    print(f"Finished: {len(entries)} Jastrow entries saved to {OUT}")
    print("Attach jastrow-lookups-2.json in the Claude chat.")

if __name__ == "__main__":
    try: main()
    except KeyboardInterrupt: print("\nStopped. Run the script again to continue.")
